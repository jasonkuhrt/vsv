import type { Manifest } from '#lib/manifest/schema'
import type { Schema } from 'effect'
import { schemaToTs } from './schema-to-ts.ts'

const FILE_HEADER = '// GENERATED by @jasonkuhrt/vsv — do not edit\n\n'

const hasAst = (u: unknown): u is { ast: unknown } => {
  if (u === null) return false
  if (typeof u !== 'object' && typeof u !== 'function') return false
  return 'ast' in u
}

const asSchema = (u: unknown): Schema.Schema.All | undefined => {
  if (u === undefined) return undefined
  if (!hasAst(u)) return undefined
  return u as Schema.Schema.All
}

export const emitRegistries = (manifest: Manifest): string => {
  const parts: string[] = [FILE_HEADER]

  parts.push('export type CommandRegistry = {\n')
  for (const cmd of manifest.commands ?? []) {
    const argsSchema = asSchema(cmd.args)
    const resultSchema = asSchema(cmd.result)
    const argsTs = argsSchema ? schemaToTs(argsSchema) : 'unknown'
    const resultTs = resultSchema ? schemaToTs(resultSchema) : 'unknown'
    parts.push(`  ${JSON.stringify(cmd.id)}: { args: ${argsTs}; result: ${resultTs} }\n`)
  }
  parts.push('}\n\n')

  parts.push('export type ExternalCommandRegistry = {\n')
  for (const cmd of manifest.externalCommands ?? []) {
    const argsSchema = asSchema(cmd.args)
    const resultSchema = asSchema(cmd.result)
    const argsTs = argsSchema ? schemaToTs(argsSchema) : 'unknown'
    const resultTs = resultSchema ? schemaToTs(resultSchema) : 'unknown'
    parts.push(`  ${JSON.stringify(cmd.id)}: { args: ${argsTs}; result: ${resultTs} }\n`)
  }
  parts.push('}\n\n')

  parts.push('export type ContextKeyRegistry = {\n')
  for (const ck of manifest.contextKeys ?? []) {
    const valueSchema = asSchema(ck.valueType)
    const valueTs = valueSchema ? schemaToTs(valueSchema) : 'unknown'
    parts.push(`  ${JSON.stringify(ck.name)}: ${valueTs}\n`)
  }
  parts.push('}\n\n')

  parts.push('export type ConfigRegistry = {\n')
  for (const c of manifest.config ?? []) {
    const valueSchema = asSchema(c.valueSchema)
    const valueTs = valueSchema ? schemaToTs(valueSchema) : 'unknown'
    parts.push(`  ${JSON.stringify(c.key)}: ${valueTs}\n`)
  }
  parts.push('}\n\n')

  parts.push('export type StateRegistry = {\n')
  for (const s of manifest.state ?? []) {
    const valueSchema = asSchema(s.valueSchema)
    const valueTs = valueSchema ? schemaToTs(valueSchema) : 'unknown'
    const scopeLiteral = JSON.stringify(s.scope)
    parts.push(`  ${JSON.stringify(s.key)}: { value: ${valueTs}; scope: ${scopeLiteral} }\n`)
  }
  parts.push('}\n')

  return parts.join('')
}
