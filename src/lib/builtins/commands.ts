// Prebuilt catalog of VS Code **core** command ids, typed.
//
// Every entry is an `ExternalCommandDecl` (a command provided by VS Code core,
// not owned by a consuming extension), so calling one through
// `runtime.executeExternalCommand(id)` types the id without re-contributing it.
//
// The args/result shapes of core commands are not individually modeled here:
// the conservative typed default is `args: Schema.Unknown` (most core commands
// take zero or one positional argument whose shape varies per command) and
// `result: Schema.Void` (most are fire-and-forget). A consumer that needs a
// precise arity for a specific command can re-declare that single id with a
// tighter `ExternalCommandDecl` in its own manifest.
//
// Scope: VS Code **core** only — the `editor.action.*`, `workbench.action.*`,
// `list.*`, and built-in `git.*` command space. Ids contributed by third-party
// or user extensions are intentionally excluded (they are not vsv-owned core
// vocabulary). Source of truth: `~/repo-references/vscode/` plus the key-binder
// command reference (see Phase B research). Imports only `effect` +
// `#lib/manifest`, so this module stays in vsv's pure subset.

