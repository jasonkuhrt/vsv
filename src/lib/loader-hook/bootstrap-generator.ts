import { Effect, FileSystem, Path, Schema, String } from 'effect';
import { asJsonObject, readPackageJson } from '#lib/codegen/sync-package-json';
import type { JsonObject } from '#lib/codegen/sync-package-json';

const encodeSpecifier = Schema.encodeEffect(
  Schema.fromJsonString(Schema.String),
);

export type Mode = 'cjs' | 'esm';

export interface BootstrapInputs {
  readonly consumerRoot: string;
  readonly entrySource?: string;
}

export interface BootstrapResult {
  readonly bootstrapPath: string;
  readonly mode: Mode;
  readonly content: string;
  readonly warnings: ReadonlyArray<string>;
}

export const detectMode = (packageJson: JsonObject): Mode => {
  if (packageJson['type'] === 'module') return 'esm';
  return 'cjs';
};

export const cjsBootstrap = Effect.fnUntraced(function* (entrySource: string) {
  const relPath = yield* encodeSpecifier(
    `./${String.replace(/^\/+/, '')(entrySource)}`,
  );
  return `// bootstrap.cjs — generated by @jasonkuhrt/vsv, do not edit
require('tsx/cjs')
module.exports = require(${relPath})
`;
});

export const esmBootstrap = Effect.fnUntraced(function* (entrySource: string) {
  const relPath = yield* encodeSpecifier(
    `./${String.replace(/^\/+/, '')(entrySource)}`,
  );
  return `// bootstrap.mjs — generated by @jasonkuhrt/vsv, do not edit
import { register } from 'tsx/esm/api'
register()
const mod = await import(${relPath})
export const activate = mod.activate
export const deactivate = mod.deactivate
`;
});

export const generateBootstrap = Effect.fnUntraced(function* (
  inputs: BootstrapInputs,
) {
  const fs = yield* FileSystem.FileSystem;
  const path = yield* Path.Path;
  const { consumerRoot } = inputs;
  const entrySource = inputs.entrySource ?? 'src/extension.ts';

  const packageJsonPath = path.join(consumerRoot, 'package.json');
  const packageJson = yield* readPackageJson(packageJsonPath);

  const warnings: string[] = [];
  const devDeps = asJsonObject(packageJson['devDependencies']) ?? {};
  const deps = asJsonObject(packageJson['dependencies']) ?? {};
  if (devDeps['tsx'] === undefined && deps['tsx'] === undefined) {
    warnings.push(
      'tsx is not listed in devDependencies or dependencies — add it with `bun add -d tsx`',
    );
  }

  const mode = detectMode(packageJson);
  const fileName = mode === 'cjs' ? 'bootstrap.cjs' : 'bootstrap.mjs';
  const bootstrapPath = path.join(consumerRoot, fileName);
  const content = yield* mode === 'cjs'
    ? cjsBootstrap(entrySource)
    : esmBootstrap(entrySource);

  yield* fs.writeFileString(bootstrapPath, content);

  const mainField = packageJson['main'];
  const expectedMain = `./${fileName}`;
  if (
    typeof mainField === 'string' &&
    mainField !== expectedMain &&
    mainField !== fileName
  ) {
    warnings.push(
      `package.json "main" is "${mainField}" but vsv expects "${expectedMain}" — update manually if this is not the intended entry`,
    );
  }

  const result: BootstrapResult = { bootstrapPath, mode, content, warnings };
  return result;
});
