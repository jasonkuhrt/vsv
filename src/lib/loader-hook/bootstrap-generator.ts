import * as path from 'node:path'

export type Mode = 'cjs' | 'esm'

export interface BootstrapInputs {
  consumerRoot: string
  entrySource?: string
}

export interface BootstrapResult {
  bootstrapPath: string
  mode: Mode
  content: string
  warnings: string[]
}

type JsonObject = { [k: string]: unknown }

const asJsonObject = (u: unknown): JsonObject | undefined => {
  if (u === null || typeof u !== 'object' || Array.isArray(u)) return undefined
  return u as JsonObject
}

export const detectMode = (packageJson: JsonObject): Mode => {
  if (packageJson['type'] === 'module') return 'esm'
  return 'cjs'
}

export const cjsBootstrap = (entrySource: string): string => {
  const relPath = `./${entrySource.replace(/^\/+/, '')}`
  return `// bootstrap.cjs — generated by @jasonkuhrt/vsv, do not edit
require('tsx/cjs')
module.exports = require(${JSON.stringify(relPath)})
`
}

export const esmBootstrap = (entrySource: string): string => {
  const relPath = `./${entrySource.replace(/^\/+/, '')}`
  return `// bootstrap.mjs — generated by @jasonkuhrt/vsv, do not edit
import { register } from 'tsx/esm/api'
register()
const mod = await import(${JSON.stringify(relPath)})
export const activate = mod.activate
export const deactivate = mod.deactivate
`
}

export const generateBootstrap = async (inputs: BootstrapInputs): Promise<BootstrapResult> => {
  const { consumerRoot } = inputs
  const entrySource = inputs.entrySource ?? 'src/extension.ts'

  const packageJsonPath = path.join(consumerRoot, 'package.json')
  const rawJson: unknown = await Bun.file(packageJsonPath).json()
  const packageJson = asJsonObject(rawJson)
  if (packageJson === undefined) {
    throw new Error(`Expected package.json at ${packageJsonPath} to be a JSON object`)
  }

  const warnings: string[] = []
  const devDeps = asJsonObject(packageJson['devDependencies']) ?? {}
  const deps = asJsonObject(packageJson['dependencies']) ?? {}
  if (devDeps['tsx'] === undefined && deps['tsx'] === undefined) {
    warnings.push(
      'tsx is not listed in devDependencies or dependencies — add it with `bun add -d tsx`',
    )
  }

  const mode = detectMode(packageJson)
  const fileName = mode === 'cjs' ? 'bootstrap.cjs' : 'bootstrap.mjs'
  const bootstrapPath = path.join(consumerRoot, fileName)
  const content = mode === 'cjs' ? cjsBootstrap(entrySource) : esmBootstrap(entrySource)

  await Bun.write(bootstrapPath, content)

  const mainField = packageJson['main']
  const expectedMain = `./${fileName}`
  if (typeof mainField === 'string' && mainField !== expectedMain && mainField !== fileName) {
    warnings.push(
      `package.json "main" is "${mainField}" but vsv expects "${expectedMain}" — update manually if this is not the intended entry`,
    )
  }

  return { bootstrapPath, mode, content, warnings }
}
